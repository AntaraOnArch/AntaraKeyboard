    private fun regionalFlag(code: String): String = buildString {
        code.uppercase().forEach { letter ->
            require(letter in 'A'..'Z')

            appendCodePoint(
                0x1F1E6 + (letter.code - 'A'.code)
            )
        }
    }

    private fun subdivisionFlag(tag: String): String = buildString {
        // Crna zastava kao baza
        appendCodePoint(0x1F3F4)

        tag.lowercase().forEach { letter ->
            if (letter in 'a'..'z') {
                appendCodePoint(
                    0xE0061 + (letter.code - 'a'.code)
                )
            }
        }

        // Cancel tag
        appendCodePoint(0xE007F)
    }

